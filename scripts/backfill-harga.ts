async function main() {
  let updated = 0;
  let notFound: string[] = [];

  for (const [namaUpper, harga] of Object.entries(HARGA_MAP)) {
    const item = await db.item.findFirst({
      where: { nama: { equals: namaUpper, mode: "insensitive" } },
    });
    if (!item) {
      notFound.push(namaUpper);
      continue;
    }
    await db.item.update({ where: { id: item.id }, data: { harga } });
    updated++;
  }

  console.log(`Backfill selesai: ${updated} item diupdate harganya.`);
  if (notFound.length > 0) {
    console.log(`${notFound.length} nama tidak ketemu di database (mungkin sudah diedit/dihapus):`);
    console.log(notFound.join(", "));
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
